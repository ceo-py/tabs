/* TABS 90 — app logic
   Data source: data/songs.json (generated by site_build.py)
   To add songs: drop the PNG in out_gz/ (or out/) and re-run site_build.py. */

const $ = (s, r = document) => r.querySelector(s);
const $$ = (s, r = document) => [...r.querySelectorAll(s)];

/* safe binding: a missing element must never take the whole page down */
function on(sel, ev, fn) {
  const el = $(sel);
  if (el) el.addEventListener(ev, fn);
  return el;
}

const state = {
  all: [],
  view: [],
  filter: 'all',
  q: '',
};

const CHANNEL_SHORT = {
  GuitarZero2HeroExpress: 'GZ',
  BernadetteTeachesMusic: 'BTM',
};

/* ---------- data -------------------------------------------------- */
/* the build stamp comes from index.html and busts any stale CDN copy
   of songs.json */
const BUILD = (document.querySelector('meta[name="site-build"]') || {}).content || '';
const MANIFEST = 'data/songs.json' + (BUILD ? '?v=' + BUILD : '');

async function load() {
  const res = await fetch(MANIFEST, { cache: 'no-cache' });
  if (!res.ok) throw new Error('songs.json: HTTP ' + res.status);
  const data = await res.json();
  state.all = data.songs || [];
  await loadShapes();
  renderStats(data);
  apply();
}

/* the fretboard shapes of the chords — needed by the legend strip */
async function loadShapes() {
  if (!window.Chords) return;
  try {
    const res = await fetch('data/chord_shapes.json' + (BUILD ? '?v=' + BUILD : ''),
      { cache: 'no-cache' });
    if (res.ok) Chords.setShapes(await res.json());
  } catch (err) {
    console.warn('chord shapes unavailable:', err.message);
  }
}

function renderStats(data) {
  const total = state.all.length;
  const rock = state.all.filter(s => s.rock).length;
  const chans = new Set(state.all.map(s => s.channel)).size;
  $('#statTotal').textContent = total;
  $('#statRock').textContent = rock;
  $('#statChannels').textContent = chans;
}

/* ---------- filtering -------------------------------------------- */
function matches(s) {
  if (state.filter === 'rock' && !s.rock) return false;
  if (state.filter !== 'all' && state.filter !== 'rock' && s.channel !== state.filter) return false;
  if (state.q) {
    const q = state.q.toLowerCase();
    const hay = (s.title + ' ' + s.artist + ' ' + s.channel + ' ' + (s.tag || '')).toLowerCase();
    if (!hay.includes(q)) return false;
  }
  return true;
}

function apply() {
  state.view = state.all.filter(matches);
  const n = state.view.length;
  $('#count').textContent = n + (n === 1 ? ' CARD' : ' CARDS');
  $('#empty').hidden = n !== 0;
  paint();
}

/* ---------- rendering -------------------------------------------- */
function esc(s) {
  return String(s ?? '').replace(/[&<>"']/g, c => (
    { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]
  ));
}

function paint() {
  const grid = $('#grid');
  grid.innerHTML = state.view.map((s, i) => `
    <article class="card" data-i="${i}" tabindex="0" role="button"
             aria-label="${esc(s.title)} — ${esc(s.artist)}">
      <div class="card__img">
        ${s.tag ? `<span class="card__tag">${esc(s.tag)}</span>` : ''}
        ${s.rock ? `<span class="card__rock">ROCK</span>` : ''}
        <img loading="lazy" decoding="async" src="${esc(s.thumb)}"
             width="${s.thumbW}" height="${s.thumbH}"
             alt="Tabs: ${esc(s.title)} — ${esc(s.artist)}">
      </div>
      <div class="card__body">
        <h3 class="card__title">${esc(s.title)}</h3>
        <p class="card__artist">${esc(s.artist)}</p>
        <p class="card__ch">${esc(CHANNEL_SHORT[s.channel] || s.channel)}</p>
      </div>
    </article>`).join('');
}

/* ---------- lightbox --------------------------------------------- */
const lb = $('#lb');
let current = null;
let lastCard = null;

function ytId(s) {
  if (!s.url) return '';
  try { return new URL(s.url).searchParams.get('v') || ''; } catch { return ''; }
}

function openLB(s) {
  current = s;
  $('#lbTitle').textContent = s.title;
  $('#lbArtist').textContent = s.artist + ' · ' + (s.tag || '');

  // embedded YouTube player at the top of the card
  const id = ytId(s);
  const pl = $('#lbPlayer');
  if (id) {
    // origin= is required by YouTube for embeds (otherwise: "Error 153")
    const origin = encodeURIComponent(location.origin);
    pl.src = 'https://www.youtube-nocookie.com/embed/' + id +
      '?rel=0&modestbranding=1&playsinline=1&enablejsapi=1&origin=' + origin;
    $('#lbPlayerWrap').style.display = '';
  } else {
    pl.removeAttribute('src');
    $('#lbPlayerWrap').style.display = 'none';
  }

  const img = $('#lbImg');
  img.src = s.card;
  img.alt = 'Tabs: ' + s.title + ' — ' + s.artist;
  paintLegend(s);
  $('#lbBody').classList.remove('is-zoom');
  lb.hidden = false;
  document.body.classList.add('lb-open');
  document.body.style.overflow = 'hidden';
  $('#lbBody').scrollTop = 0;
}

/* the chord legend strip — fretboard diagrams for the chords of this card.
   Cards that already show a fretboard diagram in the video have no
   `chords` list in the manifest, so nothing is drawn for them. */
function paintLegend(s) {
  const box = $('#lbChords');
  const row = $('#lbChordsRow');
  const chords = (s && s.chords) || [];
  if (!row || !box) return;
  if (!chords.length || !window.Chords) {
    row.innerHTML = '';
    box.hidden = true;
    return;
  }
  row.innerHTML = Chords.legend(chords);
  box.hidden = false;
}

function closeLB(back) {
  lb.hidden = true;
  document.body.classList.remove('lb-open');
  $('#lbPlayer').removeAttribute('src');   // stop playback
  document.body.style.overflow = '';
  current = null;
  /* closing takes you back to the card you opened */
  if (back && lastCard) {
    const card = lastCard;
    lastCard = null;
    requestAnimationFrame(() => {
      card.scrollIntoView({ block: 'center', behavior: 'smooth' });
      card.focus({ preventScroll: true });
    });
  }
}

document.addEventListener('click', e => {
  const card = e.target.closest('.card');
  if (card) {
    lastCard = card;
    openLB(state.view[+card.dataset.i]);
    return;
  }
  if (e.target.closest('#lbClose') || e.target.id === 'lb') closeLB(true);
  /* only the empty space around the card closes it — the chord strip and
     the picture itself must stay interactive */
  else if (e.target.id === 'lbBody') closeLB(true);
});

document.addEventListener('keydown', e => {
  if (e.key === 'Escape' && !lb.hidden) closeLB();
});

/* zoom toggle on the image itself */
on('#lbBody', 'click', e => {
  if (e.target.id === 'lbImg') {
    $('#lbBody').classList.toggle('is-zoom');
  }
});

/* keyboard activation of cards */
document.addEventListener('keydown', e => {
  if ((e.key === 'Enter' || e.key === ' ') && e.target.classList?.contains('card')) {
    e.preventDefault();
    lastCard = e.target;
    openLB(state.view[+e.target.dataset.i]);
  }
});

/* ---------- controls ---------------------------------------------- */
on('#q', 'input', e => {
  state.q = e.target.value.trim();
  apply();
});

on('#chips', 'click', e => {
  const b = e.target.closest('.chip');
  if (!b) return;
  $$('.chip').forEach(c => c.classList.toggle('is-on', c === b));
  state.filter = b.dataset.f;
  apply();
});

/* ---------- go ---------------------------------------------------- */
load().catch(err => {
  console.error(err);
  $('#count').textContent = 'Failed to load data: ' + err.message;
});
